function findAnswer(q: string): string | null {
  const normalized = q.toLowerCase().trim();
  for (const item of QA) {
    if (item.keys.some(k => normalized.includes(k.toLowerCase()) || k.toLowerCase().includes(normalized))) {
      return item.answer;
    }
  }
  // fuzzy: check if any word of length >2 matches
  const words = normalized.split(/\s+/).filter(w => w.length > 2);
  for (const item of QA) {
    for (const k of item.keys) {
      const kLower = k.toLowerCase();
      if (words.some(w => kLower.includes(w))) return item.answer;
    }
  }
  return null;
}

